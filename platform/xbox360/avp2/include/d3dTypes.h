#define D3DRGBA(r, g, b, a) \
	((D3DCOLOR)(((DWORD)((a) * 255) << 24) | ((DWORD)((r) * 255) << 16) | ((DWORD)((g) * 255) << 8) | (DWORD)((b) * 255)))
#define D3DRGB(r, g, b) (0xff000000u | ((DWORD)((r) * 255) << 16) | ((DWORD)((g) * 255) << 8) | (DWORD)((b) * 255))
#define RGBA_MAKE(r, g, b, a) ((D3DCOLOR)(((DWORD)(a) << 24) | ((DWORD)(r) << 16) | ((DWORD)(g) << 8) | (DWORD)(b)))
#define RGB_MAKE(r, g, b) RGBA_MAKE(r, g, b, 0xff)
#define RGBA_GETALPHA(c) ((c) >> 24)
#define RGBA_GETRED(c) (((c) >> 16) & 0xff)
#define RGBA_GETGREEN(c) (((c) >> 8) & 0xff)
#define RGBA_GETBLUE(c) ((c) & 0xff)

